def text_rects(s, x, y, px, color, extra=""):
    """Return SVG rects for string s; merges horizontal runs per glyph row."""
    out = []
    cx = x
    for ch in s:
        g = F.get(ch.upper(), F[' '])
        for r, row in enumerate(g):
            c = 0
            while c < 5:
                if row[c] == '1':
                    start = c
                    while c < 5 and row[c] == '1':
                        c += 1
                    out.append(f'<rect x="{cx+start*px}" y="{y+r*px}" width="{(c-start)*px}" height="{px}" fill="{color}"{extra}/>')
                else:
                    c += 1
        cx += 6 * px
    return out

def text_width(s, px):
    return len(s) * 6 * px - px
